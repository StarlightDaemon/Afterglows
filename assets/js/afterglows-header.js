/* =========================================
   AFTERGLOWS — UNIFIED HEADER + BACK NAVIGATION
   Generated by StarlightDaemon Project

   ONE canonical script, linked by root-absolute path
   (/assets/js/afterglows-header.js) from every page, exactly like the
   theme/font controller (/assets/js/afterglows-settings.js). It injects
   two floating controls so no page carries its own header/back markup:

     - .ag-header  : text-only "Afterglows" wordmark (no logo image),
                     fixed top-left. Links to the site root.
     - .ag-back    : a fixed WRAPPER holding a static .ag-back-link,
                     fixed bottom-left. Same fixed-wrapper / static-child
                     structure the settings gear uses (.ag-settings +
                     .ag-gear), so both float and stay visible on scroll.
                     Gear = bottom-right, back = bottom-left, wordmark =
                     top-left; the three never overlap.

   Back-navigation hierarchy (one level UP, not always the root):
     - Root home (/) ................... no back control (it IS home).
     - A subsite hub (matrix_code/index,
       retro/crt_demo, concepts gallery) . back to the Afterglows root.
     - A demo sub-page (matrix_code/demo_*) back to its own hub. These
       pages declare it with  <html data-ag-back="index.html">  so the
       target is explicit rather than guessed from the URL.

   iframe guard: the matrix_code hub embeds the demo pages in a preview
   <iframe>. Chrome belongs to the top-level page only, so injection is
   skipped whenever the document is framed — the embedded demo stays
   clean, but the SAME page opened standalone gets its full chrome.
   No framework, no build step.
   ========================================= */
(function () {
    'use strict';

    // Chrome is for the top-level page only. Inside the matrix hub's
    // preview iframe (or any embed) we inject nothing.
    if (window.self !== window.top) { return; }

    var root = document.documentElement;

    /* Root home == the site root index, with no subdirectory in the
       path. '/', '/index.html' -> home. Anything deeper is not. */
    function isRootHome() {
        var p = window.location.pathname.replace(/index\.html?$/i, '');
        return p === '/' || p === '';
    }

    /* Explicit per-page override wins (demo sub-pages point at their
       hub); otherwise every non-home page falls back to the root. */
    function backTarget() {
        var explicit = root.getAttribute('data-ag-back');
        if (explicit) { return explicit; }
        if (isRootHome()) { return null; }
        return '/index.html';
    }

    function build() {
        if (document.querySelector('.ag-header')) { return; } // idempotent

        /* ---- wordmark (top-left) ---- */
        var header = document.createElement('div');
        header.className = 'ag-header';

        var brand = document.createElement('a');
        brand.className = 'ag-brand';
        brand.href = '/';
        brand.textContent = 'Afterglows';
        brand.setAttribute('aria-label', 'Afterglows — home');

        var tagline = document.createElement('span');
        tagline.className = 'ag-tagline';
        tagline.textContent = 'Experimental Archive';

        header.appendChild(brand);
        header.appendChild(tagline);
        document.body.appendChild(header);

        /* ---- back control (bottom-left) ---- */
        var target = backTarget();
        if (target) {
            var wrap = document.createElement('div');
            wrap.className = 'ag-back';

            var link = document.createElement('a');
            link.className = 'ag-back-link';
            link.href = target;
            link.setAttribute('aria-label', 'Back');
            link.innerHTML =
                '<span class="ag-back-arrow" aria-hidden="true">&#9664;</span>' +
                '<span>Back</span>';

            wrap.appendChild(link);
            document.body.appendChild(wrap);
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', build, { once: true });
    } else {
        build();
    }
}());
