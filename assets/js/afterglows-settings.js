/* =========================================
   AFTERGLOWS — UNIFIED SETTINGS CONTROLLER
   Generated by StarlightDaemon Project

   ONE canonical script, linked by root-absolute path
   (/assets/js/afterglows-settings.js) from every subsite. It is the
   single source of truth for site-wide theme + font, replacing the
   three divergent implementations that used to live in
   assets/js/theme-toggle.js (root), matrix_code/index.html +
   demo_themes.html (phosphor_theme.js UIs) and retro/crt_demo.html
   (inline copy).

   What it does:
     - Applies the persisted color theme + font to <html> as early as
       possible (data-phosphor / data-font), before first paint, so
       there is no flash of the default theme.
     - Injects an identical gear-button + panel control (bottom-right)
       into every page. No per-page markup needed, so the functional
       switcher is guaranteed consistent everywhere.
     - Persists to ONE storage key each and live-syncs across tabs
       (and same-origin iframes) via the 'storage' event.

   Storage contract:
     'afterglows-phosphor'  -> one of p1 p31 p3 p4 p7 p2 p14 neon
                               (p1 clears data-phosphor; matches the
                               matrix_tools.css / crt_tools.css API)
     'afterglows-font'      -> one of ibm vt323 space fira

   Exposes window.AfterglowsSettings = {
     THEMES, FONTS,
     getPhosphor(), setPhosphor(key),
     getFont(), setFont(key),
     onPhosphorChange(fn), onFontChange(fn)
   }
   No framework, no build step.
   ========================================= */
(function () {
    'use strict';

    var THEMES = [
        { key: 'p1',   name: 'Green',       swatch: '#00ff41', note: 'P1 — classic green screen' },
        { key: 'p31',  name: 'Fast Green',  swatch: '#7be8a4', note: 'P31 — Amdek / DEC / Tektronix' },
        { key: 'p3',   name: 'Amber',       swatch: '#ffb000', note: 'P3 — DEC VT220 / Hercules' },
        { key: 'p4',   name: 'Paper White', swatch: '#f2f7ff', note: 'P4 — TRS-80 / Commodore PET' },
        { key: 'p7',   name: 'Blue-White',  swatch: '#a9d7ff', note: 'P7 — radar / oscilloscope cascade' },
        { key: 'p2',   name: 'Stoplight',   swatch: '#00ffa2', note: 'P2 — long-persistence oscillography' },
        { key: 'p14',  name: 'Violet',      swatch: '#a37bff', note: 'P14 — rare blue-violet' },
        { key: 'neon', name: 'Neon Blue',   swatch: '#00c8ff', note: 'modern cyberpunk — not a phosphor' }
    ];

    var FONTS = [
        { key: 'ibm',   name: 'IBM' },
        { key: 'vt323', name: 'VT323' },
        { key: 'space', name: 'Space' },
        { key: 'fira',  name: 'Fira' }
    ];

    var PHOSPHOR_KEY = 'afterglows-phosphor';
    var FONT_KEY = 'afterglows-font';
    var DEFAULT_PHOSPHOR = 'p1';
    var DEFAULT_FONT = 'ibm';

    var root = document.documentElement;
    var phosphorListeners = [];
    var fontListeners = [];

    function isTheme(key) { return THEMES.some(function (t) { return t.key === key; }); }
    function isFont(key) { return FONTS.some(function (f) { return f.key === key; }); }

    function readStore(key) {
        try { return localStorage.getItem(key); } catch (e) { return null; }
    }
    function writeStore(key, value) {
        try { localStorage.setItem(key, value); } catch (e) { /* private mode */ }
    }

    /* ---- one-time migration from the three legacy schemes ---- */
    // Root used 'theme' (5 colors) + 'site-font' (4 fonts). Map the two
    // retired colors onto their nearest survivor; fonts map 1:1.
    var LEGACY_THEME_MAP = {
        'p1-green': 'p1', 'p1-matrix': 'p1', 'p3-amber': 'p3',
        'p4-white': 'p4', 'ibm-blue': 'neon'
    };
    function migrateLegacy() {
        if (!readStore(PHOSPHOR_KEY)) {
            var oldTheme = readStore('theme');
            if (oldTheme && LEGACY_THEME_MAP[oldTheme]) {
                writeStore(PHOSPHOR_KEY, LEGACY_THEME_MAP[oldTheme]);
            }
        }
        if (!readStore(FONT_KEY)) {
            var oldFont = readStore('site-font');
            if (oldFont && isFont(oldFont)) {
                writeStore(FONT_KEY, oldFont);
            }
        }
    }

    /* ---- apply to the document ---- */
    function applyPhosphor(key, persist) {
        if (!isTheme(key)) { return; }
        if (key === DEFAULT_PHOSPHOR) {
            root.removeAttribute('data-phosphor');
        } else {
            root.setAttribute('data-phosphor', key);
        }
        if (persist) { writeStore(PHOSPHOR_KEY, key); }
        phosphorListeners.forEach(function (fn) { fn(key); });
    }

    function applyFont(key, persist) {
        if (!isFont(key)) { return; }
        root.setAttribute('data-font', key);
        if (persist) { writeStore(FONT_KEY, key); }
        fontListeners.forEach(function (fn) { fn(key); });
    }

    function currentPhosphor() { return root.getAttribute('data-phosphor') || DEFAULT_PHOSPHOR; }
    function currentFont() { return root.getAttribute('data-font') || DEFAULT_FONT; }

    /* ---- boot: query param wins (preview / deep link, not persisted),
       else persisted, else default. Runs immediately (before body) so
       the correct theme is on <html> at first paint. ---- */
    migrateLegacy();

    var params = new URLSearchParams(window.location.search);
    var qp = params.get('phosphor');
    if (qp && isTheme(qp)) {
        applyPhosphor(qp, false);
    } else {
        var storedP = readStore(PHOSPHOR_KEY);
        applyPhosphor(storedP && isTheme(storedP) ? storedP : DEFAULT_PHOSPHOR, false);
    }

    var qf = params.get('font');
    if (qf && isFont(qf)) {
        applyFont(qf, false);
    } else {
        var storedF = readStore(FONT_KEY);
        applyFont(storedF && isFont(storedF) ? storedF : DEFAULT_FONT, false);
    }

    /* ---- cross-tab + same-origin-iframe live sync ---- */
    window.addEventListener('storage', function (e) {
        if (e.key === PHOSPHOR_KEY && e.newValue && isTheme(e.newValue)) {
            applyPhosphor(e.newValue, false);
            syncPanel();
        } else if (e.key === FONT_KEY && e.newValue && isFont(e.newValue)) {
            applyFont(e.newValue, false);
            syncPanel();
        }
    });

    /* ---- the injected control ---- */
    var panelEl = null;

    function buildControl() {
        if (document.querySelector('.ag-settings')) { return; } // idempotent

        var wrap = document.createElement('div');
        wrap.className = 'ag-settings';

        var gear = document.createElement('button');
        gear.type = 'button';
        gear.className = 'ag-gear';
        gear.setAttribute('aria-label', 'Theme and font settings');
        gear.setAttribute('aria-expanded', 'false');
        gear.innerHTML = '<span aria-hidden="true">⚙</span>';

        var panel = document.createElement('div');
        panel.className = 'ag-panel';
        panel.setAttribute('role', 'group');
        panel.setAttribute('aria-label', 'Theme and font settings');

        // Color group
        var colorGroup = document.createElement('div');
        var colorLabel = document.createElement('p');
        colorLabel.className = 'ag-group-label';
        colorLabel.textContent = 'CRT Phosphor';
        colorGroup.appendChild(colorLabel);

        var swatches = document.createElement('div');
        swatches.className = 'ag-swatches';
        THEMES.forEach(function (t) {
            var b = document.createElement('button');
            b.type = 'button';
            b.className = 'ag-swatch';
            b.dataset.theme = t.key;
            b.style.setProperty('--ag-swatch-color', t.swatch);
            b.title = t.note;
            b.setAttribute('aria-label', t.name + ' — ' + t.note);
            b.innerHTML =
                '<span class="ag-chip" aria-hidden="true"></span>' +
                '<span class="ag-chip-label">' + t.name.split(' ')[0] + '</span>';
            b.addEventListener('click', function () { setPhosphor(t.key); });
            swatches.appendChild(b);
        });
        colorGroup.appendChild(swatches);
        panel.appendChild(colorGroup);

        // Font group
        var fontGroup = document.createElement('div');
        var fontLabel = document.createElement('p');
        fontLabel.className = 'ag-group-label';
        fontLabel.textContent = 'Terminal Font';
        fontGroup.appendChild(fontLabel);

        var fonts = document.createElement('div');
        fonts.className = 'ag-fonts';
        FONTS.forEach(function (f) {
            var b = document.createElement('button');
            b.type = 'button';
            b.className = 'ag-font-btn';
            b.dataset.font = f.key;
            b.textContent = f.name;
            b.addEventListener('click', function () { setFont(f.key); });
            fonts.appendChild(b);
        });
        fontGroup.appendChild(fonts);
        panel.appendChild(fontGroup);

        gear.addEventListener('click', function (e) {
            e.stopPropagation();
            var open = panel.classList.toggle('ag-open');
            gear.setAttribute('aria-expanded', open ? 'true' : 'false');
        });

        document.addEventListener('click', function (e) {
            if (!wrap.contains(e.target)) {
                panel.classList.remove('ag-open');
                gear.setAttribute('aria-expanded', 'false');
            }
        });
        document.addEventListener('keydown', function (e) {
            if (e.key === 'Escape' && panel.classList.contains('ag-open')) {
                panel.classList.remove('ag-open');
                gear.setAttribute('aria-expanded', 'false');
                gear.focus();
            }
        });

        wrap.appendChild(gear);
        wrap.appendChild(panel);
        document.body.appendChild(wrap);
        panelEl = panel;
        syncPanel();
    }

    function syncPanel() {
        if (!panelEl) { return; }
        var p = currentPhosphor();
        var f = currentFont();
        panelEl.querySelectorAll('.ag-swatch').forEach(function (b) {
            b.classList.toggle('ag-active', b.dataset.theme === p);
            b.setAttribute('aria-pressed', b.dataset.theme === p ? 'true' : 'false');
        });
        panelEl.querySelectorAll('.ag-font-btn').forEach(function (b) {
            b.classList.toggle('ag-active', b.dataset.font === f);
            b.setAttribute('aria-pressed', b.dataset.font === f ? 'true' : 'false');
        });
    }

    /* ---- public setters ---- */
    function setPhosphor(key) { applyPhosphor(key, true); syncPanel(); }
    function setFont(key) { applyFont(key, true); syncPanel(); }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', buildControl, { once: true });
    } else {
        buildControl();
    }

    window.AfterglowsSettings = {
        THEMES: THEMES,
        FONTS: FONTS,
        getPhosphor: currentPhosphor,
        setPhosphor: setPhosphor,
        getFont: currentFont,
        setFont: setFont,
        onPhosphorChange: function (fn) { phosphorListeners.push(fn); },
        onFontChange: function (fn) { fontListeners.push(fn); }
    };
}());
