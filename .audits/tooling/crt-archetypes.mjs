// CRT archetype visual-distinctiveness capture.
//
// Loads the REAL retro demo page (retro/crt_demo.html) over the local static
// server, then for each hardware archetype clicks the page's own TUBE button
// (the same control a real user uses), waits a settle period, and takes one
// real unmanipulated screenshot of the full demo grid (the CRT display area).
//
// Usage:
//   node .audits/tooling/crt-archetypes.mjs [--port 3100] [--settle 1400]
//
// Output: captures/crt-arch-<key>.png per archetype + one JSON line each.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import puppeteer from "puppeteer-core";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CHROME =
  process.env.CHROME_PATH ||
  "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";

const args = process.argv.slice(2);
function opt(name, dflt) {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : dflt;
}
const PORT = parseInt(opt("port", "3100"), 10);
const SETTLE = parseInt(opt("settle", "1400"), 10);
const OUT = path.resolve(opt("out", path.join(__dirname, "captures")));
fs.mkdirSync(OUT, { recursive: true });

const browser = await puppeteer.launch({
  executablePath: CHROME,
  headless: true,
  args: ["--force-device-scale-factor=1"],
});
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 1600, deviceScaleFactor: 1 });
await page.goto(`http://127.0.0.1:${PORT}/retro/crt_demo.html`, {
  waitUntil: "networkidle2",
  timeout: 60000,
});

// The TUBE buttons are generated by the page's own script.
await page.waitForSelector('#archetypeRow [data-archetype]', { timeout: 15000 });

// Pin the color to P1 through the page's own control so every archetype is
// compared under the same phosphor.
await page.click('[data-crt-color="p1"]');
await new Promise((r) => setTimeout(r, 300));

const keys = await page.$$eval('#archetypeRow [data-archetype]', (els) =>
  els.map((e) => e.dataset.archetype)
);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

for (const key of keys) {
  await page.click(`#archetypeRow [data-archetype="${key}"]`);
  await sleep(SETTLE);
  // Page-relative clip of the demo grid (the CRT display area).
  const rect = await page.evaluate(() => {
    const el = document.querySelector(".grid");
    const r = el.getBoundingClientRect();
    return {
      x: r.x + window.scrollX,
      y: r.y + window.scrollY,
      width: r.width,
      height: r.height,
    };
  });
  const applied = await page.evaluate(
    () => document.body.getAttribute("data-crt-archetype") || "(none/default)"
  );
  const file = path.join(OUT, `crt-arch-${key}.png`);
  await page.screenshot({ clip: rect, captureBeyondViewport: true }).then((buf) =>
    fs.writeFileSync(file, buf)
  );
  console.log(JSON.stringify({ key, applied, rect, file }));
}

await browser.close();
